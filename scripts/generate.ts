import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

// Support the vocabulary in the pinned export; fail on unfamiliar schema shapes.
type Schema = Record<string, any>;
const root = new URL("../", import.meta.url);
const raw = readFileSync(new URL("openapi.json", root), "utf8");
const document = JSON.parse(raw);
const metadata = JSON.parse(readFileSync(new URL("openapi.metadata.json", root), "utf8"));
const sha256 = createHash("sha256").update(raw).digest("hex");
if (sha256 !== metadata.sha256) throw new Error("OpenAPI hash changed; review the contract and update openapi.metadata.json first.");
const schemas: Record<string, Schema> = document.components.schemas;
const quote = JSON.stringify;
function type(schema: Schema): string {
  if (schema.$ref) return schema.$ref.split("/").at(-1);
  if (schema.enum) return schema.enum.map(quote).join(" | ");
  if (schema.anyOf) return schema.anyOf.map(type).join(" | ");
  switch (schema.type) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `Array<${type(schema.items)}>`;
    case "object": {
      const fields = Object.entries<Schema>(schema.properties ?? {}).map(([name, value]) =>
        `  ${quote(name)}${schema.required?.includes(name) ? "" : "?"}: ${type(value)};`);
      if (schema.additionalProperties) fields.push(`  [key: string]: ${schema.additionalProperties === true ? "unknown" : type(schema.additionalProperties)};`);
      return fields.length ? `{\n${fields.join("\n")}\n}` : "Record<string, unknown>";
    }
    case undefined:
      if (Object.keys(schema).every(key => ["title", "description", "default"].includes(key))) return "unknown";
  }
  throw new Error(`Unsupported schema: ${quote(schema)}`);
}
const banner = `// Generated by scripts/generate.ts from openapi.json. DO NOT EDIT.\n// SHA-256: ${sha256}; verified ${metadata.verifiedAt}.\n`;
const wire = banner + Object.entries(schemas).map(([name, schema]) => `export type ${name} = ${type(schema)};`).join("\n\n") + "\n";
const selected: Record<string, Schema> = {};
function include(name: string) {
  if (selected[name]) return;
  const schema = schemas[name];
  if (!schema) throw new Error(`Missing schema ${name}`);
  selected[name] = schema;
  function visit(value: unknown) {
    if (!value || typeof value !== "object") return;
    if ("$ref" in value) include(String(value.$ref).split("/").at(-1)!);
    for (const child of Object.values(value)) visit(child);
  }
  visit(schema);
}
for (const name of ["MyOrganizationOut", "ProjectOut", "ScanListItemOut", "ScanDetailOut", "FindingOut"]) include(name);
const validation = banner + 'import type { Schema } from "../schema.js";\n\nexport const schemas: Record<string, Schema> = ' + JSON.stringify(selected, null, 2) + ";\n";
mkdirSync(new URL("src/generated/", root), { recursive: true });
for (const [path, content] of [["src/generated/wire.ts", wire], ["src/generated/schemas.ts", validation]] as const) {
  if (process.argv.includes("--check")) {
    if (readFileSync(new URL(path, root), "utf8") !== content) throw new Error(`Stale generated file: ${path}`);
  } else writeFileSync(new URL(path, root), content);
}
console.log(`Verified ${Object.keys(schemas).length} wire schemas (${sha256}).`);
